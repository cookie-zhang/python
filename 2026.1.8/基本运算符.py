# 4. 逻辑运算符 
# 1）逻辑运算符的含义 

# 与(and): 表示两个条件都必须满足，在Python中用and表示。例如：and表示a必须大于0且b必须小于0。
# 或(or): 表示两个条件中任意一个满足即可，在Python中用or表示。例如：or表示a大于0或b小于0任一成立即可。
# 非(not): 表示对条件取反，在Python中用not表示。例如：not表示a不小于0。
# 2）例题1:逻辑运算符的使用 

# 示例分析:
# 设,
# print(a>0 and b<0)输出True，因为两个条件都满足
# print(a>0 or b>0)输出True，因为满足
# print(not a<0)输出True，因为为假，取反后为真
# 3）连续多个and的运算 

# 运算规则: 连续多个and运算时，所有条件都必须为真结果才为真。例如：10>0 and 5>0 and 3<0结果为False，因为最后一个条件不满足。
# 混合运算: 当and和or混合使用时，and的优先级高于or。例如：10>0 and 5>0 or 3<0先计算and部分得到True，再与or运算，最终结果为True。
