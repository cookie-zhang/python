
# ---一、基本运算符 
# 1. 算术运算符 

# 基本组成：包含加减乘除、取余、幂次方和取模运算
# 加法运算：如10 + 3 = 13
# 减法运算：如10 - 3 = 7
# 乘法运算：a * b如10 * 3 = 30
# 除法运算：结果为浮点数 如10 / 3 ≈ 3.333
# 取余运算：得到除法余数 如10 % 3 = 1
# 幂运算：a  b表示a的b次方 如10  3 = 1000
# 取模运算：得到商的整数部分 如10 // 3 = 3
# 特殊说明：Python不支持自增(++)和自减(--)运算符
# 2. 比较运算符 

# 运算类型：用于比较两个值的大小关系
# 大于：如10 > 3返回True
# 大于等于：如10 >= 3返回True
# 小于：如10 < 3返回False
# 小于等于：如10 <= 3返回False
# 等于：如10 == 3返回False
# 不等于：使用叹号等号组合 如10 != 3返回True
# 返回值特点：所有比较运算都返回布尔值(True/False)
